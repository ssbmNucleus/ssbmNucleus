"""The shield bubble per fighter, from the vanilla ISO, for Watch Lite (meleeRender.js shieldAt).

Each fighter's shield bone (ft_data->x8->x11) is posed by forward kinematics through its guard
pose (shieldlib.py, ftCo_Guard.c): untilted, at full tilt every 5 degrees of the smoothed guard
angle (Guard figatree, submotion 38), and during GuardSetOff by GuardDamage frame (submotion 40).
Centres are relative to the fighter position (TopN = Slippi x/y), facing +1, world units, rounded
to 4 places and then compacted to 3 (as JavaScript Math.round does).

    app/venv/Scripts/python.exe -B tools/liteaudit/shield_table/build.py [--iso PATH] [--out PATH]

Writes app/frontend/src/tracker/replays/data/shieldTable.js:
    export default {"source": ..., "common": {PlCo ftCommonData x10 x44C x260 x264 x2D4 x2D8},
                    "chars": {"<internal cid>": {s: radius at full health (modelScale x shieldSize),
                              n: GuardOn ramp frames, on: GuardOn start centre (approx.),
                              g: untilted Guard centre, tilt: [[x, y]] every 5 degrees 0..360
                              (0 = toward facing, 90 = up), dmg: [[x, y]] by GuardDamage frame}}}
Yoshi (14) guards with his egg: only s and g (the shield bone in the rest pose), no tilt.
"""
import argparse
import json
import math
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[3]
DATA = REPO / 'app/frontend/src/tracker/replays/data'
sys.path[1:1] = [str(REPO / 'tools/liteaudit'), str(REPO / 'app/backend')]

STEP = 5
# The payload's own description. Kept word for word: the committed data carries it.
SOURCE = ('Shield bubble per fighter from the vanilla ISO (round7/shield/build_table.py): radius = modelScale x '
          'shieldSize; centre relative to TopN, facing +1, world units. tilt: centre at full tilt every 5 degrees '
          'of the smoothed guard angle (0 = forward, 90 = up); dmg: centre in GuardSetOff by action frame; g: '
          'untilted Guard centre; on: GuardOn start pose (approx.); n: GuardOn ramp frames.')
COMMON = ['x10', 'x44C', 'x260', 'x264', 'x2D4', 'x2D8']
HEADER = ("// The shield bubble per fighter, read from the vanilla ISO: each fighter's shield\n"
          "// bone (ft_data->x8->x11) posed by forward kinematics through its guard pose, its\n"
          "// tilt animation every 5 degrees and its GuardDamage animation (Pl*.dat, Pl*AJ.dat;\n"
          "// common constants from PlCo.dat). Generated by tools/liteaudit/shield_table/build.py;\n"
          "// do not edit by hand. See meleeRender.js shieldAt.\n")


# ---------------------------------------------------------------- JavaScript-identical output
def js_round(v, places):
    """Math.round(v * 10^places) / 10^places (ties toward +infinity, as V8)."""
    k = 10 ** places
    x = v * k
    r = math.ceil(x)
    if r - 0.5 > x:
        r -= 1
    return r / k


def js_number(v):
    """Number.prototype.toString / JSON.stringify for a number."""
    if isinstance(v, (bool, np.bool_)):
        raise TypeError('bool')
    if isinstance(v, (int, np.integer)):
        return str(int(v))
    v = float(v)
    if v != v or v in (math.inf, -math.inf):
        return 'null'
    if v == 0:
        return '0'
    s = repr(v)
    sign = '-' if s[0] == '-' else ''
    s = s.lstrip('-')
    mant, _, exp = s.partition('e')
    ip, _, fp = mant.partition('.')
    digits = ip + fp
    n = len(ip) + (int(exp) if exp else 0)
    stripped = digits.lstrip('0')
    n -= len(digits) - len(stripped)
    digits = stripped.rstrip('0')
    k = len(digits)
    if k <= n <= 21:
        out = digits + '0' * (n - k)
    elif 0 < n <= 21:
        out = digits[:n] + '.' + digits[n:]
    elif -6 < n <= 0:
        out = '0.' + '0' * -n + digits
    else:
        e = n - 1
        out = digits[0] + ('.' + digits[1:] if k > 1 else '') + 'e' + ('+' if e >= 0 else '-') + str(abs(e))
    return sign + out


def _index_key(k):
    return k.isdigit() and (k == '0' or k[0] != '0') and int(k) < 2 ** 32 - 1


def js_stringify(o):
    """JSON.stringify(o): no spaces, integer-like object keys first in ascending order."""
    if o is None:
        return 'null'
    if isinstance(o, str):
        return json.dumps(o, ensure_ascii=False)
    if isinstance(o, dict):
        keys = [str(k) for k in o]
        vals = dict(zip(keys, o.values()))
        order = sorted((k for k in keys if _index_key(k)), key=int) + [k for k in keys if not _index_key(k)]
        return '{' + ','.join(json.dumps(k, ensure_ascii=False) + ':' + js_stringify(vals[k]) for k in order) + '}'
    if isinstance(o, (list, tuple)):
        return '[' + ','.join(js_stringify(v) for v in o) + ']'
    return js_number(o)


# ---------------------------------------------------------------- table
def r4(v):
    return [round(float(x), 4) for x in v]


def r3(v):
    return js_round(v, 3)


def centre(f, srts):
    from shieldlib import to_world
    m, _ = f.shield_local(srts)
    return np.array(to_world(m[:3, 3], f.model_scale, 1))


def build(d):
    from shieldlib import SM_GUARDDAMAGE, SM_GUARDON, CommonData, Fighter
    co = CommonData(d)
    out = {'source': SOURCE, 'common': {k: round(co.f(int(k[1:], 16)), 6) for k in COMMON}, 'chars': {}}
    for cid in range(27):
        f = Fighter(d, cid)
        s = r3(round(f.model_scale, 4) * round(f.shield_size, 4))
        if cid == 14:
            # Yoshi: ftYs_Shield_8012C1D4 -> 8006FA58(costume rest pose); no tilt, no size scaling.
            g = r4(centre(f, f.rest()))
            out['chars'][str(cid)] = {'s': s, 'g': [r3(g[0]), r3(g[1])]}
            continue
        sn = f.part_node[f.shield_part]
        wait = next(a.index for a in (f.other[0] if f.other else f.fd).actions if a.motion in ['Wait1', 'Wait'])
        ws = f.anim_srts(wait, 0)
        ws[sn].t = [0.0, 0.0, 0.0]                      # 800921DC zeroes the shield bone translation
        on = r4(centre(f, ws))
        g = r4(centre(f, f.guard_pose(10, 0)))
        tilt = [r4(centre(f, f.guard_pose(10 + deg, 1))) for deg in range(0, 361, STEP)]
        dend = f.anim(SM_GUARDDAMAGE)[0]
        dmg = [r4(centre(f, f.anim_srts(SM_GUARDDAMAGE, fr))) for fr in range(int(math.ceil(dend)) + 1)]
        out['chars'][str(cid)] = {'s': s, 'n': int(f.anim(SM_GUARDON)[0]), 'on': [r3(on[0]), r3(on[1])],
                                  'g': [r3(g[0]), r3(g[1])], 'tilt': [[r3(x), r3(y)] for x, y, _ in tilt],
                                  'dmg': [[r3(x), r3(y)] for x, y, _ in dmg]}
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--iso', type=Path, default=None, help='vanilla Melee ISO (default: the one the app knows)')
    ap.add_argument('--out', type=Path, default=DATA / 'shieldTable.js')
    args = ap.parse_args()
    from stage_bake import FighterDisc
    if args.iso is None:
        from shared.vanilla_extract.vanilla_refs import known_vanilla_iso
        args.iso = Path(str(known_vanilla_iso()))
    table = build(FighterDisc(args.iso))
    args.out.write_text(HEADER + 'export default ' + js_stringify(table) + ';\n', encoding='utf-8')
    print(f'{args.out.name}: {len(table["chars"])} fighters, {args.out.stat().st_size} bytes')


if __name__ == '__main__':
    main()
