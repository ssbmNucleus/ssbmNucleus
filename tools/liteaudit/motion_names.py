"""The game's own animation for each fighter-specific action state, where the
slippilab charmaps name is not in that fighter's animation archive.

Each fighter's motion state table in the melee decomp (ft/chara/ftXx/*.c,
"// ftXx_MS_Name = N" followed by its submotion ftXx_SM_Anim) names the
animation the game plays for that state. Where charmaps.json's name for a
state (animationMap, specialsMap or the action name) is missing from the
character's archive but the decomp's submotion is present (exactly, or
without a trailing _N / N variant suffix), record it. Kirby's copies of
Pichu, Dr. Mario and Roy have no archive animation of their own; they stand
in with his copies of Pikachu, Mario and Marth (the same moves). meleeRender
.fallbackFor reads the result. Common states (0..340) are handled there by
name.

    python tools/liteaudit/motion_names.py [--decomp PATH] [--anim-zips PATH]

Writes app/frontend/src/tracker/replays/data/motionNames.js (a module, so
Node tests import it without a JSON loader):
    export default { "<internal cid>": { "<state>": "AnimName" } }
"""
import argparse
import json
import os
import re
import zipfile
from pathlib import Path

from extract_anims import ZIP_NAMES

REPO = Path(__file__).resolve().parents[2]
REPLAYS = REPO / 'app/frontend/src/tracker/replays'
# internal character id -> decomp fighter directory (Nana shares Popo's table)
DIRS = ['ftMario', 'ftFox', 'ftCaptain', 'ftDonkey', 'ftKirby', 'ftKoopa', 'ftLink', 'ftSeak', 'ftNess', 'ftPeach',
        'ftPopo', 'ftNana', 'ftPikachu', 'ftSamus', 'ftYoshi', 'ftPurin', 'ftMewtwo', 'ftLuigi', 'ftMars', 'ftZelda',
        'ftCLink', 'ftDrMario', 'ftFalco', 'ftPichu', 'ftGameWatch', 'ftGanon', 'ftEmblem']


# Kirby's copy prefix -> the copy whose move it is (Pichu: Pikachu's Thunder
# Jolt, Dr. Mario: Mario's fireball, Roy: Marth's Shield Breaker).
COPY_TWIN = {'Pc': 'Pk', 'Dr': 'Mr', 'Fe': 'Ms'}


def motion_table(folder):
    table = {}
    for f in sorted(folder.glob('*.c')):
        s = f.read_text(encoding='utf-8', errors='ignore')
        for ms, n, sm in re.findall(r'//\s*(ft\w+?_MS_\w+)\s*=\s*(\d+)\s*\n\s*([\w\-]+)\s*,', s):
            table[int(n)] = sm
    return table


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--decomp', type=Path, default=Path(os.environ.get('MELEE_DECOMP') or Path.home() / 'projects' / 'melee'))
    ap.add_argument('--anim-zips', type=Path,
                    default=Path(os.environ.get('LOCALAPPDATA', '')) / 'SSBM Nucleus/storage/nucleome/anim_zips')
    args = ap.parse_args()
    charmaps = json.loads((REPO / 'app/backend/tracker/tools/charmaps.json').read_text(encoding='utf-8'))
    out = {}
    for cid, folder in enumerate(DIRS):
        pack = {n[:-5] for n in zipfile.ZipFile(args.anim_zips / f'{ZIP_NAMES[cid]}.zip').namelist() if n.endswith('.json')}
        ch = charmaps['chars'].get(str(cid))
        if not ch:
            continue
        for state, sm in sorted(motion_table(args.decomp / 'src/melee/ft/chara' / folder).items()):
            if state < 341 or not sm.startswith('ft'):
                continue
            action = charmaps['actionNameById'][state] if state < len(charmaps['actionNameById']) else None
            names = [ch['animationMap'].get(action) if action else None, ch['specialsMap'].get(str(state)), action]
            if any(n and n in pack for n in names):
                continue
            anim = re.sub(r'^ft\w\w_SM_', '', sm)
            twins = [re.sub(r'^(Pc|Dr|Fe)', lambda m: COPY_TWIN[m.group(1)], anim)] if cid == 4 else []
            # an item swing of the fighter's own (Captain Falcon's bat smash):
            # the common swing every zip has, as meleeRender's stand-in does
            swing = re.match(r'^(?:Bat|Parasol|Lip[Ss]tick|StarRod|Harisen)Swing(\d)', anim)
            swings = [f'Swing{swing.group(1)}', 'Swing1'] if swing else []
            for candidate in (anim, re.sub(r'_\d+$', '', anim), re.sub(r'\d+$', '', anim), *twins, *swings):
                if candidate in pack:
                    out.setdefault(str(cid), {})[str(state)] = candidate
                    break
    path = REPLAYS / 'data/motionNames.js'
    path.write_text("// Generated by tools/liteaudit/motion_names.py from the melee decomp's motion\n"
                    '// tables and the animation zips. Do not edit by hand.\n'
                    'export default ' + json.dumps(out, separators=(',', ':'), sort_keys=True) + '\n', encoding='utf-8')
    print(f'motionNames.js: {sum(len(v) for v in out.values())} states over {len(out)} characters')


if __name__ == '__main__':
    main()
