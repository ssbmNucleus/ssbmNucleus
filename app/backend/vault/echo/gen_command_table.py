"""
gen_command_table.py -- regenerate `_command_table.py` from HSDRawViewer's
authoritative subaction specs (shipped in the pinned HSDRawViewer build,
app/utility/hsdraw/win-x64/Scripts) (Scripts/command_controls.yml +
command_fighter.yml). Run from backend/:

    python -m vault.echo.gen_command_table

The generated module is committed so the runtime needs neither PyYAML nor the
HSDRawViewer source tree (packaged builds do not ship it).
"""
from __future__ import annotations

import re
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
# The Scripts/ folder ships in the prebuilt HSDRawViewer (python tools/build/fetch_native.py hsdlib).
SCRIPTS = HERE.parents[2] / "utility" / "hsdraw" / "win-x64" / "Scripts"
OUT = HERE / "_command_table.py"


def snake(name: str) -> str:
    s = re.sub(r"\(.*?\)", "", name)          # "(bugged)" etc.
    s = re.sub(r"[^0-9A-Za-z]+", "_", s).strip("_").lower()
    return s or "field"


def load(path: Path):
    return yaml.safe_load(path.read_text(encoding="utf-8-sig"))


def main():
    cmds = []
    for fn in ("command_controls.yml", "command_fighter.yml"):
        for c in load(SCRIPTS / fn):
            seen: dict[str, int] = {}
            params = []
            for p in c.get("parameters") or []:
                key = snake(p["name"])
                if key == "none":
                    key = "_pad"
                n = seen.get(key, 0) + 1
                seen[key] = n
                if n > 1:
                    key = f"{key}_{n}"
                params.append({
                    "key": key,
                    "name": p["name"],
                    "bits": int(p["bitCount"]),
                    "signed": bool(p.get("signed", False)),
                    "hex": bool(p.get("hex", False)),
                    "enums": [str(e) for e in p["enums"]] if p.get("enums") else None,
                })
            bits = 6 + sum(p["bits"] for p in params) if params else 32
            if bits % 8:
                raise SystemExit(f"code {c['code']} {c['name']}: {bits} bits not byte aligned")
            cmds.append({"code": int(c["code"]), "name": c["name"],
                         "key": snake(c["name"]), "bits": bits, "params": params})
    cmds.sort(key=lambda c: c["code"])
    codes = [c["code"] for c in cmds]
    assert codes == list(range(len(codes))), "command codes must be contiguous"

    lines = ['"""GENERATED by vault/echo/gen_command_table.py from HSDRawViewer',
             'Scripts/command_controls.yml + command_fighter.yml -- do not edit."""',
             "", "COMMAND_TABLE = ["]
    for c in cmds:
        lines.append(f"    {{'code': {c['code']}, 'name': {c['name']!r}, 'key': {c['key']!r}, 'bits': {c['bits']}, 'params': [")
        for p in c["params"]:
            lines.append(f"        {p!r},")
        lines.append("    ]},")
    lines.append("]")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(cmds)} commands)")


if __name__ == "__main__":
    main()
