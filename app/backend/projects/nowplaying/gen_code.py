"""Regenerate the Now Playing instruction words in `code_words.py` (dev-only;
the output is committed, so no assembler runs at create or export).

Requires devkitPPC (assembler only).  Run from app/backend:
    python -m projects.nowplaying.gen_code
"""
import subprocess
import tempfile
from pathlib import Path

AS = Path(r"C:/devkitPro/devkitPPC/bin/powerpc-eabi-as.exe")
OBJCOPY = Path(r"C:/devkitPro/devkitPPC/bin/powerpc-eabi-objcopy.exe")
HERE = Path(__file__).resolve().parent


def assemble() -> list[int]:
    with tempfile.TemporaryDirectory() as tmp:
        obj, binf = Path(tmp) / "now_playing.o", Path(tmp) / "now_playing.bin"
        subprocess.run([str(AS), "-mgekko", "-mregnames", "-o", str(obj),
                        str(HERE / "now_playing.s")], check=True)
        subprocess.run([str(OBJCOPY), "-O", "binary", str(obj), str(binf)], check=True)
        data = binf.read_bytes()
    if len(data) % 4:
        raise RuntimeError("now_playing.s assembled to a partial word")
    words = [int.from_bytes(data[i:i + 4], "big") for i in range(0, len(data), 4)]
    if words[-1] != 0x4E800020:
        raise RuntimeError("now_playing.s must end with the replaced blr")
    return words


def main():
    words = assemble()
    rows = [", ".join(f"0x{w:08X}" for w in words[i:i + 4]) for i in range(0, len(words), 4)]
    out = ('"""Generated by gen_code.py from now_playing.s -- do not edit by hand."""\n\n'
           "WORDS = (\n" + "".join(f"    {r},\n" for r in rows) + ")\n")
    (HERE / "code_words.py").write_text(out, encoding="utf-8")
    print(f"code_words.py: {len(words)} words")


if __name__ == "__main__":
    main()
