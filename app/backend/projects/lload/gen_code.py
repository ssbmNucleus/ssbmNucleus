"""Regenerate the L-load instruction words in `code_words.py` (dev-only; the
output is committed, so no assembler runs at export).

Assembles `lload.s` (empty group table) with devkitPPC and splits the words
around the table: everything before `bl after_table`, and everything after the
table. `code.py` puts a project's table back in between.

Requires devkitPPC (assembler only).  Run:  python -m projects.lload.gen_code
"""
import subprocess
import tempfile
from pathlib import Path

AS = Path(r"C:/devkitPro/devkitPPC/bin/powerpc-eabi-as.exe")
OBJCOPY = Path(r"C:/devkitPro/devkitPPC/bin/powerpc-eabi-objcopy.exe")
HERE = Path(__file__).resolve().parent

# lload.s: four prologue words, the `bl`, one word of empty table, then the body.
PREFIX_WORDS = 4
TABLE_WORD = PREFIX_WORDS + 1


def assemble() -> list[int]:
    with tempfile.TemporaryDirectory() as tmp:
        obj, binf = Path(tmp) / "lload.o", Path(tmp) / "lload.bin"
        subprocess.run([str(AS), "-mgekko", "-mregnames", "-o", str(obj), str(HERE / "lload.s")],
                       check=True)
        subprocess.run([str(OBJCOPY), "-O", "binary", str(obj), str(binf)], check=True)
        data = binf.read_bytes()
    words = [int.from_bytes(data[i:i + 4], "big") for i in range(0, len(data), 4)]
    if words[PREFIX_WORDS] >> 26 != 18 or words[TABLE_WORD] != 0:
        raise RuntimeError("lload.s no longer has the prologue/bl/empty-table shape gen_code expects")
    return words


def _fmt(name: str, words: list[int]) -> str:
    rows = [", ".join(f"0x{w:08X}" for w in words[i:i + 4]) for i in range(0, len(words), 4)]
    return f"{name} = (\n" + "".join(f"    {r},\n" for r in rows) + ")\n"


def main():
    words = assemble()
    out = ('"""Generated by gen_code.py from lload.s -- do not edit by hand."""\n\n'
           + _fmt("PREFIX", words[:PREFIX_WORDS]) + "\n"
           + _fmt("BODY", words[TABLE_WORD + 1:]))
    (HERE / "code_words.py").write_text(out, encoding="utf-8")
    print(f"code_words.py: {PREFIX_WORDS} prefix + {len(words) - TABLE_WORD - 1} body words")


if __name__ == "__main__":
    main()
